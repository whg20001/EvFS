import { expect, test, type Page } from '@playwright/test';
import type { PublicState } from '@sanxing/contracts';
import { password } from './settings.ts';
import { answerDialog, autoAcceptDialogs } from './dialog.ts';
const state = async (page: Page): Promise<PublicState> => (await page.request.get('/api/state')).json();

test('mock 偏好→学习出代码题→移动端编辑运行→预检提交→模型反馈', async ({ page }) => {
  await page.clock.setFixedTime(new Date('2026-08-12T04:00:00Z'));
  await page.goto('/review'); await page.getByLabel('访问密码').fill(password); await page.getByRole('button', { name: '进入我的学习空间' }).click();
  await page.goto('/review'); await page.locator('#learning-preferences summary').click();
  const prefs = page.locator('#learning-preferences');
  await prefs.getByRole('checkbox', { name: '代码题', exact: true }).check();
  await prefs.getByRole('checkbox', { name: 'JavaScript', exact: true }).check();
  await prefs.getByRole('checkbox', { name: 'Python', exact: true }).uncheck();
  await expect(prefs.getByRole('checkbox', { name: 'JavaScript', exact: true })).toBeDisabled();
  await prefs.getByRole('button', { name: '确认保存设置' }).click(); await answerDialog(page, false, ['代码题：开启', 'JavaScript']);
  await expect(prefs.getByRole('button', { name: '确认保存设置' })).toBeEnabled();
  await prefs.getByRole('button', { name: '确认保存设置' }).click(); await answerDialog(page, true, ['代码题：开启', 'JavaScript']);
  await expect(prefs.getByRole('status')).toContainText('设置已保存');
  await page.reload(); await page.locator('#learning-preferences summary').click();
  await expect(prefs.getByRole('checkbox', { name: '代码题', exact: true })).toBeChecked();
  await expect(prefs.getByRole('checkbox', { name: 'JavaScript', exact: true })).toBeChecked();
  await autoAcceptDialogs(page);
  await page.goto('/recite'); await page.getByRole('button', { name: '开始今天的三省' }).click();
  await page.getByRole('textbox', { name: '今天学了什么', exact: true }).fill('字符串可以按关键词切分，用于统计关键词不重叠出现的次数。');
  await page.getByRole('button', { name: '提交复述', exact: true }).click();
  await expect(page.getByRole('checkbox', { name: /纳入这个知识点/ }).first()).toBeVisible();
  for (const checkbox of await page.getByRole('checkbox', { name: /纳入这个知识点/ }).all()) await checkbox.check();
  await page.getByRole('button', { name: '确认学习范围' }).click();
  await page.getByRole('button', { name: '结束追问，准备测验' }).click();
  await page.getByRole('link', { name: '开始 / 继续测验' }).click();
  await page.locator('.options .option').first().click();
  await page.getByLabel('我的回答', { exact: true }).fill('使用切分结果的长度减一，注意不重叠出现和未出现的边界。');
  await page.getByRole('button', { name: '正式提交' }).click();
  await expect(page.getByText('代码题 · JavaScript', { exact: true })).toBeVisible();
  const editor = page.getByRole('textbox', { name: '代码答案' });
  await expect(editor).toContainText('TODO');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.emulateMedia({ colorScheme: 'dark' });
  await editor.fill(''); await page.getByRole('button', { name: '暂存答案' }).click();
  await expect.poll(async () => (await state(page)).quizzes.at(-1)!.questions.at(-1)!.hasDraft).toBe(true);
  await page.reload(); await expect(editor).toHaveText('');
  await page.getByRole('button', { name: '重置为骨架' }).click(); await expect(editor).toContainText('TODO');
  await page.getByRole('button', { name: '运行测试', exact: true }).click();
  await expect(page.locator('.code-output')).toContainText('测试未通过');
  const implementation = 'function countMentions(text, keyword) {\n  return text.split(keyword).length - 1;\n}';
  await editor.fill(implementation);
  await expect(page.locator('.code-output')).toHaveCount(0);
  await page.getByRole('button', { name: '运行测试', exact: true }).click();
  await expect(page.locator('.code-output')).toContainText('测试通过 · 2 / 2');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true);
  await page.screenshot({ path: 'test-results/code-exercise-mobile-dark.png', fullPage: true });
  const preview = page.waitForRequest(request => request.url().includes('/input-preview') && request.postDataJSON().execution?.passed === 2);
  await page.getByRole('button', { name: '正式提交' }).click();
  expect((await preview).postDataJSON().text).toBe(implementation);
  await expect(page.getByRole('button', { name: '完成测验，查看结果' })).toBeEnabled();
  await page.getByRole('button', { name: '完成测验，查看结果' }).click();
  await expect(editor).toHaveCount(0);
  await expect(page.locator('iframe[title="代码运行沙箱"]')).toHaveCount(1);
  await expect(page.locator('.question-feedback').last()).toContainText('脚本演示');
  await expect(page.locator('.question-feedback').last().locator('.code-block').first()).toHaveText(implementation);
  await expect(page.locator('.question-feedback').last()).toContainText('测试通过 · 2 / 2');
  const submitted = (await state(page)).quizzes.at(-1)!.questions.at(-1)!;
  expect(submitted.answer?.execution).toMatchObject({ status: 'passed', passed: 2, total: 2 });
  expect(submitted.answer?.assessment).toMatchObject({ status: 'needs_verification', score: null });
  // Leave subsequent tests with the original opt-out default.
  await page.goto('/review'); await page.locator('#learning-preferences summary').click();
  await prefs.getByRole('checkbox', { name: '代码题', exact: true }).uncheck();
  await prefs.getByRole('button', { name: '确认保存设置' }).click();
  await expect(prefs.getByRole('status')).toContainText('设置已保存');
});
